import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

function filesWithExtension(relativeDirectory: string, extension: string) {
  return readdirSync(join(process.cwd(), relativeDirectory), { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(extension))
    .map((entry) => join(relativeDirectory, entry.name));
}

function shippedSourceFiles(relativeDirectory: string): string[] {
  return readdirSync(join(process.cwd(), relativeDirectory), { withFileTypes: true }).flatMap(
    (entry) => {
      const relativePath = join(relativeDirectory, entry.name);
      if (entry.isDirectory()) {
        if (entry.name === "__tests__" || entry.name === "tests") {
          return [];
        }
        return shippedSourceFiles(relativePath);
      }
      return /\.(?:rs|ts|tsx)$/u.test(entry.name) && !/\.test\.[^.]+$/u.test(entry.name)
        ? [relativePath]
        : [];
    },
  );
}

