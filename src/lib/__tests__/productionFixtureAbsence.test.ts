function shippedSource(relativePath: string) {
  const source = readFileSync(join(process.cwd(), relativePath), "utf8");
  if (!relativePath.endsWith(".rs")) {
    return source;
  }
  return source.split(/\n#\[cfg\(test\)\]\nmod tests\s*\{/u, 1)[0];
}

describe("production acceptance data boundary", () => {
  it("removes the fixture-only supplier command permission", () => {
    expect(
      existsSync(
        join(
          process.cwd(),
          "src-tauri/permissions/autogenerated/run_supplier_reconciliation_audit.toml",
        ),
      ),
    ).toBe(false);
  });

  it.each(productionFiles)("keeps audited constants out of %s", (relativePath) => {
    const source = shippedSource(relativePath).toLowerCase();
    for (const signature of forbiddenProductionSignatures) {
      expect(source, `${relativePath} contains ${signature}`).not.toContain(
        signature.toLowerCase(),
      );
    }
  });
});
